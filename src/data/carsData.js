export const carsBySlug = Object.fromEntries(carsData.map((c) => [c.slug, c]));

// All unique categories
export const carCategories = ['ALL', 'PREMIUM', 'SUV', 'SEDAN', 'CONVERTIBLE', 'ECONOMY', 'FAMILY'];

// Helper: get similar cars for a given vehicle
export function getSimilarCars(vehicle, limit = 4) {
  if (!vehicle?.similar?.length) return [];
  return vehicle.similar
    .slice(0, limit)
    .map((slug) => carsBySlug[slug])
    .filter(Boolean);
}

